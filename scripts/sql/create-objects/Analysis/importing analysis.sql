SELECT [EMPLOYEE_ID]      
      ,[REVIEW_DATE]     
      ,[Id]
  FROM [HDHRP].[IPDBA].[HD_TEACHER_EVAL_RESULT] 
  WHERE EMPLOYEE_ID = '40079' 

  --UPDATE [HDHRP].[IPDBA].[HD_TEACHER_EVAL_RESULT] SET REVIEW_DATE = '2026-03-26 00:00:01'  WHERE Id= '386'

  SELECT 
    [EMPLOYEE_ID],
    [REVIEW_DATE],
    COUNT(*) AS [DuplicateCount]
FROM [HDHRP].[IPDBA].[HD_TEACHER_EVAL_RESULT]
GROUP BY 
    [EMPLOYEE_ID],
    [REVIEW_DATE]
HAVING COUNT(*) >= 2
ORDER BY [EMPLOYEE_ID], [REVIEW_DATE];
